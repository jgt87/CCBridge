// Development only (needs Node.js): writes the files of StreamHub's built-in builder in
// templates/build/ from npm packages, so the builder itself runs in Edge without Node.js.
//   node tools/update-build-tools.mjs <unpacked esbuild-wasm package folder>
// TypeScript, React and the React types come from ui-src/node_modules (npm install in ui-src first).
// Large files are stored gzipped and base64-encoded inside plain scripts: a page opened from disk can
// load a script, but not fetch a file; Edge unpacks them with DecompressionStream.
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { fileURLToPath } from 'url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = path.join(repo, 'ui-src', 'node_modules');
const out = path.join(repo, 'templates', 'build');
const esbuildDir = process.argv[2];
if (!esbuildDir || !fs.existsSync(path.join(esbuildDir, 'esbuild.wasm'))) { console.error('usage: node tools/update-build-tools.mjs <esbuild-wasm package folder>'); process.exit(1); }
fs.mkdirSync(out, { recursive: true });

const read = (p) => fs.readFileSync(p, 'utf8');
const packed = (name, data) => {
  const gz = zlib.gzipSync(Buffer.isBuffer(data) ? data : Buffer.from(data, 'utf8'), { level: 9 });
  return '/* Generated by tools/update-build-tools.mjs: do not edit. */\nwindow.' + name + ' = "' + gz.toString('base64') + '";\n';
};
const version = (dir) => JSON.parse(read(path.join(dir, 'package.json'))).version;

// esbuild (MIT): its browser API and its WebAssembly compiler.
fs.writeFileSync(path.join(out, 'esbuild.js'), '/* esbuild ' + version(esbuildDir) + ' (MIT licence, see LICENSE-esbuild.md). */\n' + read(path.join(esbuildDir, 'lib', 'browser.min.js')));
fs.writeFileSync(path.join(out, 'esbuild-wasm.js'), packed('__kitBuildWasm', fs.readFileSync(path.join(esbuildDir, 'esbuild.wasm'))));
fs.copyFileSync(path.join(esbuildDir, 'LICENSE.md'), path.join(out, 'LICENSE-esbuild.md'));

// TypeScript (Apache 2.0) with its lib files, and the React types (MIT) for checking .tsx.
const ts = path.join(nm, 'typescript');
const files = {};
for (const f of fs.readdirSync(path.join(ts, 'lib'))) if (/^lib\..*\.d\.ts$/.test(f)) files['/lib/' + f] = read(path.join(ts, 'lib', f));
const addTypes = (pkg, list) => { for (const f of list) { const p = path.join(nm, pkg, f); if (fs.existsSync(p)) files['/node_modules/' + pkg + '/' + f] = read(p); } };
addTypes('@types/react', ['package.json', 'index.d.ts', 'global.d.ts', 'jsx-runtime.d.ts', 'jsx-dev-runtime.d.ts']);
addTypes('@types/react-dom', ['package.json', 'index.d.ts', 'client.d.ts']);
addTypes('csstype', ['package.json', 'index.d.ts']);
fs.writeFileSync(path.join(out, 'typescript.js'), packed('__kitBuildTs', JSON.stringify({ code: read(path.join(ts, 'lib', 'typescript.js')), files })));
fs.copyFileSync(path.join(ts, 'LICENSE.txt'), path.join(out, 'LICENSE-typescript.txt'));
fs.writeFileSync(path.join(out, 'LICENSE-types.txt'), read(path.join(nm, '@types', 'react', 'LICENSE')) + '\n\ncsstype:\n' + read(path.join(nm, 'csstype', 'LICENSE')));

// React (MIT), production builds only, as the packages a page may import.
const v = {};
const cjs = (pkg, file) => read(path.join(nm, pkg, 'cjs', file));
v['/node_modules/react/index.js'] = "module.exports = require('./cjs/react.production.js');";
v['/node_modules/react/cjs/react.production.js'] = cjs('react', 'react.production.js');
v['/node_modules/react/jsx-runtime.js'] = "module.exports = require('./cjs/react-jsx-runtime.production.js');";
v['/node_modules/react/cjs/react-jsx-runtime.production.js'] = cjs('react', 'react-jsx-runtime.production.js');
v['/node_modules/react/jsx-dev-runtime.js'] = "module.exports = require('./cjs/react-jsx-dev-runtime.production.js');";
v['/node_modules/react/cjs/react-jsx-dev-runtime.production.js'] = cjs('react', 'react-jsx-dev-runtime.production.js');
v['/node_modules/react-dom/index.js'] = "module.exports = require('./cjs/react-dom.production.js');";
v['/node_modules/react-dom/cjs/react-dom.production.js'] = cjs('react-dom', 'react-dom.production.js');
v['/node_modules/react-dom/client.js'] = "module.exports = require('./cjs/react-dom-client.production.js');";
v['/node_modules/react-dom/cjs/react-dom-client.production.js'] = cjs('react-dom', 'react-dom-client.production.js');
v['/node_modules/scheduler/index.js'] = "module.exports = require('./cjs/scheduler.production.js');";
v['/node_modules/scheduler/cjs/scheduler.production.js'] = cjs('scheduler', 'scheduler.production.js');
fs.writeFileSync(path.join(out, 'vendor.js'), packed('__kitBuildVendor', JSON.stringify(v)));
fs.copyFileSync(path.join(nm, 'react', 'LICENSE'), path.join(out, 'LICENSE-react.txt'));

const versions = 'esbuild-wasm ' + version(esbuildDir) + '\ntypescript ' + version(ts) + '\nreact ' + version(path.join(nm, 'react')) + '\nreact-dom ' + version(path.join(nm, 'react-dom')) +
  '\nscheduler ' + version(path.join(nm, 'scheduler')) + '\n@types/react ' + version(path.join(nm, '@types', 'react')) + '\n@types/react-dom ' + version(path.join(nm, '@types', 'react-dom')) + '\n';
fs.writeFileSync(path.join(out, 'VERSIONS.txt'), versions);
for (const f of fs.readdirSync(out)) console.log(f.padEnd(26), (fs.statSync(path.join(out, f)).size / 1024 / 1024).toFixed(2), 'MB');
