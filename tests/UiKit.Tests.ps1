    }
    It 'names only classes the kit has' {
        $rule = [IO.File]::ReadAllText((Join-Path $root 'prompts\rules\uikit.md'))
        $css = [IO.File]::ReadAllText((Join-Path $root 'templates\ui-kit\kit.css'))
