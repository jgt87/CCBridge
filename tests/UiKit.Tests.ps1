Describe 'Install-UiKit' {
    $p = Join-Path $env:TEMP ('ccb-kit-' + [guid]::NewGuid().ToString('N')); New-Item -ItemType Directory $p | Out-Null
    It 'puts the whole kit in the catalogue and only the tokens and the stylesheet in styles/kit, never overwriting the project''s tokens' {
        @(Install-UiKit $p $root) -join ',' | Should Be 'styles/kit/tokens.css,styles/kit/kit.css'
        foreach ($f in 'kit.css', 'kit.js', 'kit-charts.js', 'kit-data.js', 'kit-examples.html', 'LICENSE-kokonutui.txt', 'vendor\pdfjs\pdf.min.js', 'VERSION.txt') {
            Test-Path (Join-Path $p ".streamhub\ui-kit\$f") | Should Be $true
        }
        @(Get-ChildItem (Join-Path $p 'styles\kit') -Recurse -File).Count | Should Be 2
        (Get-Content (Join-Path $p 'styles\kit\kit.css') -TotalCount 1) | Should Match '^/\* Generated by the helper program from the UI kit'
        Test-UiKitInProject $p | Should Be $true
        [IO.File]::WriteAllText((Join-Path $p 'styles\kit\tokens.css'), ':root { --kit-accent: #224466; }')
        @(Install-UiKit $p $root).Count | Should Be 0
        [IO.File]::ReadAllText((Join-Path $p 'styles\kit\tokens.css')) | Should Match '#224466'
    }
    It 'adds a React part when the code imports it, with the script and licence it needs' {
        $r = Join-Path $env:TEMP ('ccb-kitr-' + [guid]::NewGuid().ToString('N')); New-Item -ItemType Directory (Join-Path $r 'src') -Force | Out-Null
        [IO.File]::WriteAllText((Join-Path $r 'package.json'), '{ "dependencies": { "react": "^19.0.0" } }')
        $null = Install-UiKit $r $root
        Test-Path (Join-Path $r '.streamhub\ui-kit\react\HoldButton.tsx') | Should Be $true
        Test-Path (Join-Path $r 'styles\kit\react') | Should Be $false
        [IO.File]::WriteAllText((Join-Path $r 'src\App.tsx'), "import { Chart } from `"../styles/kit/react/Chart`";`nimport { HoldButton } from `"../styles/kit/react/HoldButton`";")
        $u = Update-UiKitProject $r $root
        foreach ($f in 'react/Chart.tsx', 'kit-charts.js', 'LICENSE-bklit-ui.txt', 'react/HoldButton.tsx', 'LICENSE-kokonutui.txt') { $u.added -contains "styles/kit/$f" | Should Be $true }
        $u.added -contains 'styles/kit/kit.js' | Should Be $false
        $css = [IO.File]::ReadAllText((Join-Path $r 'styles\kit\kit.css'))
        $css | Should Match '\.kit-btn--hold\.is-holding::before'
        $css | Should Match '\.kit-chart__bar'
        Remove-Item $r -Recurse -Force -ErrorAction SilentlyContinue
    }
    Remove-Item $p -Recurse -Force -ErrorAction SilentlyContinue
}

Describe 'Taking what the pages use from the catalogue' {
    $p = Join-Path $env:TEMP ('ccb-kitu-' + [guid]::NewGuid().ToString('N')); New-Item -ItemType Directory $p | Out-Null
    $null = Install-UiKit $p $root
    $css = { [IO.File]::ReadAllText((Join-Path $p 'styles\kit\kit.css')) }
    It 'writes only the rules of the kit classes in use' {
        [IO.File]::WriteAllText((Join-Path $p 'index.html'), '<body class="kit-page"><div class="kit-split"><button class="kit-btn kit-btn--primary">Go</button></div></body>')
        $u = Update-UiKitProject $p $root
        $u.updated -contains 'styles/kit/kit.css' | Should Be $true
        $c = & $css
        $c | Should Match '\.kit-btn--primary \{'
        $c | Should Match '@media \(max-width: 860px\) \{ \.kit-split'
        $c | Should Not Match 'kit-search|kit-chart|kokonutui'
        @((Update-UiKitProject $p $root).updated).Count | Should Be 0   # nothing new: left as it is
    }
    It 'adds a kit script a page loads, with its licence, and the classes the script uses' {
        [IO.File]::WriteAllText((Join-Path $p 'search.html'), '<div class="kit-search" data-kit-search><input class="kit-input"></div><script src="styles/kit/kit.js"></script>')
        $u = Update-UiKitProject $p $root
        $u.added -contains 'styles/kit/kit.js' | Should Be $true
        $u.added -contains 'styles/kit/LICENSE-kokonutui.txt' | Should Be $true
        $c = & $css
        $c | Should Match '\.kit-search__list'
        $c | Should Match 'adapted from kokonutui'
    }
    It 'takes classes made in code by prefix, and leaves pdf.js out until a page loads it' {
        [IO.File]::WriteAllText((Join-Path $p 'badge.js'), 'el.className = "kit-badge kit-badge--" + tone;')
        $null = Update-UiKitProject $p $root
        & $css | Should Match '\.kit-badge--ok'
        Test-Path (Join-Path $p 'styles\kit\vendor') | Should Be $false
        [IO.File]::WriteAllText((Join-Path $p 'read.html'), '<script src="styles/kit/vendor/pdfjs/pdf.min.js"></script><script src="styles/kit/vendor/pdfjs/pdf.worker.min.js"></script><script src="styles/kit/kit-data.js"></script>')
        $u = Update-UiKitProject $p $root
        foreach ($f in 'vendor/pdfjs/pdf.min.js', 'vendor/pdfjs/pdf.worker.min.js', 'vendor/pdfjs/LICENSE-pdfjs.txt', 'kit-data.js') { $u.added -contains "styles/kit/$f" | Should Be $true }
    }
    It 'leaves a kit.css the project made itself alone' {
        [IO.File]::WriteAllText((Join-Path $p 'styles\kit\kit.css'), '.kit-btn { color: red; }')
        $null = Update-UiKitProject $p $root
        & $css | Should Be '.kit-btn { color: red; }'
    }
    It 'refuses a change by Copilot to the generated stylesheet' {
        Import-Module (Join-Path $root 'lib\Executor.psm1')
        Remove-Item (Join-Path $p 'styles\kit\kit.css')
        $null = Update-UiKitProject $p $root
        { Assert-Writable $p 'styles/kit/kit.css' } | Should Throw 'written by the helper program'
        { Assert-Writable $p 'styles/kit/tokens.css' } | Should Not Throw
    }
    Remove-Item $p -Recurse -Force -ErrorAction SilentlyContinue
}

Describe 'Searching the kit catalogue' {
    It 'lets glob and grep find the catalogue, but not the rest of .streamhub or pdf.js' {
        Import-Module (Join-Path $root 'lib\Executor.psm1')
        $p = Join-Path $env:TEMP ('ccb-kits-' + [guid]::NewGuid().ToString('N')); New-Item -ItemType Directory $p | Out-Null
        $null = Install-UiKit $p $root
        [IO.File]::WriteAllText((Join-Path $p '.streamhub\issues.json'), '{ "note": "kit-search__list" }')
        Invoke-GlobAction $p '**/kit-examples.html' | Should Match '^\.streamhub/ui-kit/kit-examples\.html'
        Invoke-GlobAction $p '**/issues.json' | Should Match 'no files match'
        $g = Invoke-GrepAction $p 'kit-search__list'
        $g | Should Match '\.streamhub/ui-kit/kit-examples\.html:\d+:'
        $g | Should Match '\.streamhub/ui-kit/kit\.css:\d+:'
        $g | Should Not Match 'issues\.json'
        Invoke-GrepAction $p 'getDocument' | Should Not Match 'vendor/pdfjs'
        Remove-Item $p -Recurse -Force -ErrorAction SilentlyContinue
    }
}

Describe 'Select-KitCss' {
    It 'keeps the used selectors of a list, used @media rules, named keyframes and a licence note once' {
        $src = "/* header */`n.kit-a { x: 1; }`n/* Parts adapted from X (MIT licence, see LICENSE-x.txt). */`n.kit-b, .kit-c:hover { y: 2; }`n@media (max-width: 9px) { .kit-b { z: 3; } .kit-d { z: 4; } }`n.kit-e .kit-b { w: 5; }`n@keyframes kit-spin { to { a: b; } }`n.kit-b { animation: kit-spin 1s; }"
        $used = New-Object 'System.Collections.Generic.HashSet[string]'; [void]$used.Add('kit-b')
        $out = Select-KitCss $src @{ classes = $used; prefixes = @() }
        $out | Should Not Match 'header|kit-a|kit-c|kit-d|kit-e'
        $out | Should Match '(?m)^\.kit-b \{ y: 2; \}'
        $out | Should Match '@media \(max-width: 9px\) \{ \.kit-b \{ z: 3; \} \}'
        $out | Should Match '@keyframes kit-spin'
        ([regex]::Matches($out, 'MIT licence')).Count | Should Be 1
    }
}

Describe 'The UI kit rule' {
    It 'goes with the UI rules while the setting is on' {
        $ids = @(& (Get-Module Prompts) { Get-PromptModules -Text 'Build a dashboard page with a table and filters' -Context @{ Paths = @('index.html'); Traits = @('web', 'code') } })
