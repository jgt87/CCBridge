# The UI kit (templates/ui-kit, lib/UiKit.psm1): a catalogue in the project's .streamhub/ui-kit/ for
# interface work (setting uiKit), and in styles/kit/ only what the pages use; its rule goes to Copilot with the UI rules; generated-looking patterns
# are reported (Guardrails Find-UiSlop). Made-up project content.
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Import-Module (Join-Path $root 'lib\Config.psm1') -Force
Import-Module (Join-Path $root 'lib\UiKit.psm1') -Force
